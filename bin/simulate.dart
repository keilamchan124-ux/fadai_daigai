void _playNaiveBotRun(GameEngine engine) {
  if (engine.activeDraft != null) engine.selectDraftChoice(0);
  // 笨 Bot：唔識排陣拖位，唔留錢交租，見到乜亂買乜
  for (int q = 1; q <= GameEngine.maxQuarters; q++) {
    if (engine.quarterPhase == QuarterPhase.gameOver ||
        engine.quarterPhase == QuarterPhase.victory) {
      break;
    }
    if (engine.activeDraft != null) {
      if (!engine.selectDraftChoice(q % 3)) {
        engine.skipCurrentDraftForBonus();
      }
    }
    engine.openShopDraft3Choice();
    if (engine.activeDraft != null) {
      if (!engine.selectDraftChoice(0)) engine.activeDraft = null;
    }
    engine.startQuarterMarketRun();
    for (int s = 0; s < 18; s++) {
      engine.tickOneSecond();
      if (engine.quarterPhase == QuarterPhase.rescue) {
        engine.resolveRescue(true);
      }
    }
  }
}

void _playStrategicBotRun(GameEngine engine) {
  if (engine.activeDraft != null) engine.selectDraftChoice(0);
  for (var q = 0; q < 12; q++) {
    if (engine.quarterPhase != QuarterPhase.planning) break;
    for (var guard = 0; guard < 20; guard++) {
      if (engine.activeDraft == null) {
        if (engine.pendingRelicDrafts > 0) {
          engine.openRelicDraft3Choice();
        } else if (engine.pendingFreeDrafts > 0) {
          engine.openShopDraft3Choice();
        } else {
          break;
        }
      }
      final draft = engine.activeDraft!;
      var best = -1;
      var bestScore = -double.infinity;
      for (var i = 0; i < draft.choices.length; i++) {
        final copy = GameEngine(seed: 1)
          ..loadFromJsonString(engine.toJsonString());
        if (!copy.selectDraftChoice(
          i,
          replaceRelicId: copy.equippedRelicIds.firstOrNull,
        )) {
          continue;
        }
        final score = copy.previewQuarterCash();
        if (score > bestScore) {
          best = i;
          bestScore = score;
        }
      }
      if (best < 0) {
        engine.skipCurrentDraftForBonus();
        if (engine.activeDraft != null) break;
      } else {
        engine.selectDraftChoice(
          best,
          replaceRelicId: engine.equippedRelicIds.firstOrNull,
        );
      }
    }
    // Local search uses only a copy; no real rewards are generated by search.
    for (var pass = 0; pass < 2; pass++) {
      var score = engine.previewQuarterCash();
      int? bestFrom, bestTo;
      for (var from = 0; from < engine.slots.length; from++) {
        for (var to = from + 1; to < engine.slots.length; to++) {
          if (!engine.bossDefeatedInCurrentTier &&
              (from == engine.currentTier.goldenSlotIndex ||
                  to == engine.currentTier.goldenSlotIndex)) {
            continue;
          }
          final candidate = engine.previewQuarterCash(from: from, to: to);
          if (candidate > score) {
            score = candidate;
            bestFrom = from;
            bestTo = to;
          }
        }
      }
      if (bestFrom == null) break;
      engine.swapOrMoveShops(bestFrom, bestTo!);
    }
    engine.startQuarterMarketRun();
    engine.triggerTimeSkip();
    if (engine.quarterPhase == QuarterPhase.rescue) engine.resolveRescue(true);
  }
}

void main() {
  const int runsPerBot = 100;
  int naiveWins = 0;
  int strategicWins = 0;
  double naiveTotalQuarters = 0;
  double strategicTotalQuarters = 0;
  double strategicTotalPeakNW = 0;
  int strategicMergedShops = 0;

  final sw = Stopwatch()..start();
  final records=<Map<String,dynamic>>[];

  for (int r = 0; r < runsPerBot; r++) {
    final naiveEngine = GameEngine(seed: 10000 + r);
    _playNaiveBotRun(naiveEngine);
    if (naiveEngine.quarterPhase == QuarterPhase.victory) naiveWins++;
    naiveTotalQuarters += naiveEngine.currentQuarter;

    final stratEngine = GameEngine(seed: 10000 + r);
    _playStrategicBotRun(stratEngine);
    if (stratEngine.quarterPhase == QuarterPhase.victory) strategicWins++;
    strategicTotalQuarters += stratEngine.currentQuarter;
    strategicTotalPeakNW += stratEngine.peakNetWorthThisRun;
    records.add({'seed':10000+r,'naiveWon':naiveEngine.quarterPhase==QuarterPhase.victory,
      'lookaheadWon':stratEngine.quarterPhase==QuarterPhase.victory,
      'naiveQuarter':naiveEngine.currentQuarter,'lookaheadQuarter':stratEngine.currentQuarter,
      'naiveLedger':naiveEngine.quarterLedger,'lookaheadLedger':stratEngine.quarterLedger});
    strategicMergedShops += stratEngine.slots
        .where((s) => s != null && s.level >= 2)
        .length;
  }

  sw.stop();
  Directory('reports').createSync(recursive:true);
  File('reports/balance.json').writeAsStringSync(const JsonEncoder.withIndent('  ').convert({
    'runsPerBot':runsPerBot,'seedStart':10000,'naiveWins':naiveWins,'lookaheadWins':strategicWins,
    'note':'Lookahead bot previews exact future RNG. This checks solvability, not human win rate or fun.',
    'runs':records}));
  print('=== 《發達大計》Quarter-Based Roguelike 200 局對比模擬報告 ===');
  print('200 局模擬總耗時: ${sw.elapsedMilliseconds} ms');
  print(
    '【笨 Bot (亂買唔排陣)】12 季通關勝率: ${(naiveWins / runsPerBot * 100).toStringAsFixed(1)}% (平均到達第 ${(naiveTotalQuarters / runsPerBot).toStringAsFixed(1)} 季)',
  );
  print(
    '【前瞻排陣 Bot（可預覽確切結果）】12 季通關勝率: ${(strategicWins / runsPerBot * 100).toStringAsFixed(1)}% (平均到達第 ${(strategicTotalQuarters / runsPerBot).toStringAsFixed(1)} 季)',
  );
  print(
    '策略 Bot 平均每局合成 ⭐⭐/⭐⭐⭐ 街舖數: ${(strategicMergedShops / runsPerBot).toStringAsFixed(2)} 間',
  );
  print(
    '策略 Bot 平均最高身家: ${HkFormatters.money(strategicTotalPeakNW / runsPerBot)}',
  );
}
